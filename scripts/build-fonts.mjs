#!/usr/bin/env node
// build-fonts.mjs — flatten OFL fonts from node_modules/@fontsource into a
// self-contained shared/fonts.css + shared/fonts/*.woff2.
//
// Why: the templates link /shared/fonts.css, but the repo does not bundle fonts
// (README: "Fonts are not bundled"). The @fontsource packages ship per-weight
// CSS with unicode-range subsets — exactly what CJK needs — but their url()
// paths only work from inside node_modules. This script copies the woff2 files
// into shared/fonts/ and rewrites the CSS so the page can be served from any
// project root with no node_modules dependency at render time.
//
//   node scripts/build-fonts.mjs
//
// Output: shared/fonts.css, shared/fonts/<pkg>-<subset>-<weight>-normal.woff2
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const SRC = path.join(ROOT, 'node_modules', '@fontsource');
const OUT_DIR = path.join(ROOT, 'shared');
const FONT_DIR = path.join(OUT_DIR, 'fonts');

const FAMILIES = [
  'noto-sans-sc',
  'noto-serif-sc',
  'zcool-kuaile',
  'jetbrains-mono',
  'inter',
  'playfair-display',
  'orbitron',
];
const WEIGHTS = ['400', '500', '600', '700', '900'];

fs.mkdirSync(FONT_DIR, { recursive: true });

let blocks = 0;
let copied = 0;
let bytes = 0;
const out = [
  '/* generated by scripts/build-fonts.mjs — do not edit by hand */',
  '/* OFL fonts vendored locally from @fontsource; woff2 only. */',
  '',
];

for (const pkg of FAMILIES) {
  for (const w of WEIGHTS) {
    const cssPath = path.join(SRC, pkg, `${w}.css`);
    if (!fs.existsSync(cssPath)) {
      console.warn(`[skip] ${pkg}/${w}.css missing`);
      continue;
    }
    const css = fs.readFileSync(cssPath, 'utf8');
    // Split on the comment that precedes each @font-face; keep whole blocks.
    const faceRe = /@font-face\s*\{([\s\S]*?)\}/g;
    let m;
    while ((m = faceRe.exec(css)) !== null) {
      const body = m[1];
      const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
      const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim();
      const style = /font-style:\s*([^;]+);/.exec(body)?.[1]?.trim() || 'normal';
      const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
      const woff2 = /url\(([^)]+\.woff2)\)/.exec(body)?.[1];
      if (!family || !woff2) { continue; }

      const rel = woff2.replace(/^\.\//, '');
      const srcFile = path.join(SRC, pkg, rel);
      if (!fs.existsSync(srcFile)) { console.warn(`[miss] ${pkg}/${rel}`); continue; }
      const flat = `${pkg}-${path.basename(rel)}`;
      const dst = path.join(FONT_DIR, flat);
      if (!fs.existsSync(dst)) {
        fs.copyFileSync(srcFile, dst);
        copied++;
        bytes += fs.statSync(dst).size;
      }
      out.push(
        '@font-face {',
        `  font-family: '${family}';`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        `  font-display: swap;`,
        `  src: url(./fonts/${flat}) format('woff2');`,
        range ? `  unicode-range: ${range};` : '',
        '}',
        '',
      );
      blocks++;
    }
  }
}

fs.writeFileSync(path.join(OUT_DIR, 'fonts.css'), out.filter((l) => l !== null).join('\n'));
console.log(`[done] shared/fonts.css  ${blocks} @font-face blocks  ${copied} woff2 copied  ${(bytes / 1024 / 1024).toFixed(1)} MB`);
